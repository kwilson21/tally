// Spike: `node spike/baseline/gen-schema.ts` applies migrations/*.sql to a throwaway in-memory SQLite (Node's built-in
// node:sqlite, no dependency) and writes spike/baseline/schema.generated.ts. A test fails when the file is stale.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { DatabaseSync } from "node:sqlite";
import { introspect } from "./introspect.ts";

const db = new DatabaseSync(":memory:");
for (const file of readdirSync("migrations").sort()) db.exec(readFileSync(`migrations/${file}`, "utf8"));
const schema = await introspect(async (sql) => db.prepare(sql).all() as Record<string, unknown>[]);
writeFileSync(
	"spike/baseline/schema.generated.ts",
	`// Generated by gen-schema.ts from migrations/*.sql. Do not edit.\nimport type { Schema } from "./introspect.ts";\n\nexport const SCHEMA = ${JSON.stringify(schema, null, "\t")} as const satisfies Schema;\n`,
);
console.log(`${Object.keys(schema).length} tables`);
